/* ---------------- HELPER UTILITIES ---------------- */

export const getDishesByCategory = (catId) => {
  if (!catId || catId === "ALL") return foodDishes;
  return foodDishes.filter((dish) => dish.categoryId.toLowerCase() === catId.toLowerCase());
};

export const getDishesByRestaurant = (restId) => {
  if (!restId) return [];
  return foodDishes.filter((dish) => dish.restaurantId === restId);
};

export const getRestaurantById = (restId) => {
  if (!restId) return null;
  return restaurants.find((r) => r.id === restId) || null;
};

export const getPopularDishes = () => {
  return foodDishes.filter((d) => d.isBestseller);
};
